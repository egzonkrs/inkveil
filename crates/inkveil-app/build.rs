//! Windows build setup: the app icon, version information shown in Explorer, and linker
//! hardening against DLL planting.

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=assets/inkveil.ico");

    let windows_msvc = std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        && std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc");
    if !windows_msvc {
        return;
    }

    // DLLs the exe imports directly are looked up in System32 only (Windows 10 1607+), so a
    // malicious DLL placed next to inkveil.exe (e.g. in Downloads) is never loaded.
    println!("cargo:rustc-link-arg-bins=/DEPENDENTLOADFLAG:0x800");

    write_and_embed_resources();
}

fn write_and_embed_resources() {
    let version = env!("CARGO_PKG_VERSION");
    let mut numbers: Vec<u32> = version
        .split(['.', '-'])
        .filter_map(|p| p.parse().ok())
        .collect();
    numbers.resize(4, 0);
    let numeric = numbers
        .iter()
        .map(u32::to_string)
        .collect::<Vec<_>>()
        .join(",");
    let icon = std::path::Path::new(&std::env::var("CARGO_MANIFEST_DIR").expect("set by cargo"))
        .join("assets")
        .join("inkveil.ico")
        .display()
        .to_string()
        .replace('\\', "\\\\");

    let rc = format!(
        r#"// Generated by build.rs.
// Icon 1 is also what GPUI uses for the window and taskbar icon.
1 ICON "{icon}"

1 VERSIONINFO
FILEVERSION {numeric}
PRODUCTVERSION {numeric}
FILEFLAGSMASK 0x3fL
FILEFLAGS 0x0L
FILEOS 0x40004L
FILETYPE 0x1L
FILESUBTYPE 0x0L
BEGIN
    BLOCK "StringFileInfo"
    BEGIN
        BLOCK "040904b0"
        BEGIN
            VALUE "CompanyName", "Inkveil"
            VALUE "FileDescription", "Inkveil - private, local-only encrypted notes"
            VALUE "FileVersion", "{version}"
            VALUE "InternalName", "inkveil"
            VALUE "LegalCopyright", "Copyright (c) 2026 Egzon Krasniqi and Inkveil contributors. MIT OR Apache-2.0."
            VALUE "OriginalFilename", "inkveil.exe"
            VALUE "ProductName", "Inkveil"
            VALUE "ProductVersion", "{version}"
        END
    END
    BLOCK "VarFileInfo"
    BEGIN
        VALUE "Translation", 0x409, 1200
    END
END
"#
    );
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").expect("set by cargo"));
    let rc_path = out.join("inkveil.rc");
    std::fs::write(&rc_path, rc).expect("writing inkveil.rc");
    embed_resource::compile(&rc_path, embed_resource::NONE)
        .manifest_optional()
        .expect("compiling Windows resources");
}
