//! Editor actions and their default key bindings.

use gpui::{KeyBinding, actions};

/// Key context for editor bindings.
pub const CONTEXT: &str = "Editor";

actions!(
    editor,
    [
        // Typing structure
        Newline,
        SoftBreak,
        Backspace,
        DeleteForward,
        DeleteWordBackward,
        DeleteWordForward,
        Tab,
        ShiftTab,
        // Movement
        Left,
        Right,
        Up,
        Down,
        WordLeft,
        WordRight,
        LineStart,
        LineEnd,
        DocStart,
        DocEnd,
        PageUp,
        PageDown,
        SelectLeft,
        SelectRight,
        SelectUp,
        SelectDown,
        SelectWordLeft,
        SelectWordRight,
        SelectLineStart,
        SelectLineEnd,
        SelectDocStart,
        SelectDocEnd,
        SelectAll,
        // Clipboard and history
        Copy,
        Cut,
        Paste,
        PastePlain,
        Undo,
        Redo,
        // Inline formatting
        ToggleBold,
        ToggleItalic,
        ToggleUnderline,
        ToggleStrike,
        ToggleCode,
        ClearFormatting,
        EditLink,
        // Block formatting
        Paragraph,
        Heading1,
        Heading2,
        Heading3,
        BulletList,
        NumberedList,
        Checklist,
        Quote,
        CodeBlock,
        AlignLeft,
        AlignCenter,
        AlignRight,
        Indent,
        Outdent,
        InsertDivider,
        InsertTable,
        // Lines and multiple carets
        DuplicateLine,
        AddCaretAbove,
        AddCaretBelow,
        CaretsAtLineEnds,
        CollapseCarets,
    ]
);

/// Default bindings (Windows and Linux style).
pub fn key_bindings() -> Vec<KeyBinding> {
    let ctx = Some(CONTEXT);
    vec![
        KeyBinding::new("enter", Newline, ctx),
        KeyBinding::new("shift-enter", SoftBreak, ctx),
        KeyBinding::new("backspace", Backspace, ctx),
        KeyBinding::new("shift-backspace", Backspace, ctx),
        KeyBinding::new("delete", DeleteForward, ctx),
        KeyBinding::new("ctrl-backspace", DeleteWordBackward, ctx),
        KeyBinding::new("ctrl-delete", DeleteWordForward, ctx),
        KeyBinding::new("tab", Tab, ctx),
        KeyBinding::new("shift-tab", ShiftTab, ctx),
        KeyBinding::new("left", Left, ctx),
        KeyBinding::new("right", Right, ctx),
        KeyBinding::new("up", Up, ctx),
        KeyBinding::new("down", Down, ctx),
        KeyBinding::new("ctrl-left", WordLeft, ctx),
        KeyBinding::new("ctrl-right", WordRight, ctx),
        KeyBinding::new("home", LineStart, ctx),
        KeyBinding::new("end", LineEnd, ctx),
        KeyBinding::new("ctrl-home", DocStart, ctx),
        KeyBinding::new("ctrl-end", DocEnd, ctx),
        KeyBinding::new("pageup", PageUp, ctx),
        KeyBinding::new("pagedown", PageDown, ctx),
        KeyBinding::new("shift-left", SelectLeft, ctx),
        KeyBinding::new("shift-right", SelectRight, ctx),
        KeyBinding::new("shift-up", SelectUp, ctx),
        KeyBinding::new("shift-down", SelectDown, ctx),
        KeyBinding::new("ctrl-shift-left", SelectWordLeft, ctx),
        KeyBinding::new("ctrl-shift-right", SelectWordRight, ctx),
        KeyBinding::new("shift-home", SelectLineStart, ctx),
        KeyBinding::new("shift-end", SelectLineEnd, ctx),
        KeyBinding::new("ctrl-shift-home", SelectDocStart, ctx),
        KeyBinding::new("ctrl-shift-end", SelectDocEnd, ctx),
        KeyBinding::new("ctrl-a", SelectAll, ctx),
        KeyBinding::new("ctrl-c", Copy, ctx),
        KeyBinding::new("ctrl-insert", Copy, ctx),
        KeyBinding::new("ctrl-x", Cut, ctx),
        KeyBinding::new("shift-delete", Cut, ctx),
        KeyBinding::new("ctrl-v", Paste, ctx),
        KeyBinding::new("shift-insert", Paste, ctx),
        KeyBinding::new("ctrl-shift-v", PastePlain, ctx),
        KeyBinding::new("ctrl-z", Undo, ctx),
        KeyBinding::new("ctrl-y", Redo, ctx),
        KeyBinding::new("ctrl-shift-z", Redo, ctx),
        KeyBinding::new("ctrl-b", ToggleBold, ctx),
        KeyBinding::new("ctrl-i", ToggleItalic, ctx),
        KeyBinding::new("ctrl-u", ToggleUnderline, ctx),
        KeyBinding::new("ctrl-shift-x", ToggleStrike, ctx),
        KeyBinding::new("ctrl-e", ToggleCode, ctx),
        KeyBinding::new("ctrl-\\", ClearFormatting, ctx),
        KeyBinding::new("ctrl-k", EditLink, ctx),
        KeyBinding::new("ctrl-alt-0", Paragraph, ctx),
        KeyBinding::new("ctrl-alt-1", Heading1, ctx),
        KeyBinding::new("ctrl-alt-2", Heading2, ctx),
        KeyBinding::new("ctrl-alt-3", Heading3, ctx),
        KeyBinding::new("ctrl-shift-8", BulletList, ctx),
        KeyBinding::new("ctrl-shift-7", NumberedList, ctx),
        KeyBinding::new("ctrl-shift-9", Checklist, ctx),
        KeyBinding::new("ctrl-shift-.", Quote, ctx),
        KeyBinding::new("ctrl-alt-c", CodeBlock, ctx),
        KeyBinding::new("ctrl-shift-l", AlignLeft, ctx),
        KeyBinding::new("ctrl-shift-e", AlignCenter, ctx),
        KeyBinding::new("ctrl-shift-r", AlignRight, ctx),
        KeyBinding::new("ctrl-]", Indent, ctx),
        KeyBinding::new("ctrl-[", Outdent, ctx),
        KeyBinding::new("ctrl-d", DuplicateLine, ctx),
        KeyBinding::new("shift-alt-down", DuplicateLine, ctx),
        KeyBinding::new("ctrl-alt-up", AddCaretAbove, ctx),
        KeyBinding::new("ctrl-alt-down", AddCaretBelow, ctx),
        KeyBinding::new("shift-alt-i", CaretsAtLineEnds, ctx),
        KeyBinding::new("escape", CollapseCarets, ctx),
    ]
}
